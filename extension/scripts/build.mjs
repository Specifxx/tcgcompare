// Builds one Chrome extension per site config: node extension/scripts/build.mjs [siteId…] (default: every site).
// Output: extension/dist/<id>/ (load it unpacked to test) and extension/dist/<id>-<version>.zip (upload this one).
// No dependencies: the icons are committed PNGs (scripts/assets.mjs draws them once from the site's icon).
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const main = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
const ids = !main ? [] : process.argv.slice(2).length ? process.argv.slice(2) : fs.readdirSync(path.join(ROOT, "sites")).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, ""));

export function manifestFor(site) {
  const hostOf = (u) => new URL(u).origin + "/*";
  return {
    manifest_version: 3,
    name: site.name,
    short_name: site.short,
    version: site.version,
    description: site.description,
    homepage_url: site.home,
    icons: { 16: "icons/16.png", 32: "icons/32.png", 48: "icons/48.png", 128: "icons/128.png" },
    action: { default_popup: "popup.html", default_title: `${site.short} price check`, default_icon: { 16: "icons/16.png", 32: "icons/32.png" } },
    background: { service_worker: "background.js" },
    permissions: ["storage", "contextMenus", "activeTab"],
    host_permissions: [hostOf(site.feed)],
    content_scripts: [{ matches: site.matches, js: ["config.js", "shared.js", "content.js"], run_at: "document_idle" }],
    web_accessible_resources: [{ resources: ["icons/32.png"], matches: site.matches }],
  };
}

for (const id of ids) {
  const site = JSON.parse(fs.readFileSync(path.join(ROOT, "sites", `${id}.json`), "utf8"));
  if (site.description.length > 132) throw new Error(`${id}: description is ${site.description.length} chars (Chrome's limit is 132)`);
  if (site.name.length > 75) throw new Error(`${id}: name over 75 chars`);
  const out = path.join(ROOT, "dist", id);
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(path.join(out, "icons"), { recursive: true });
  for (const f of fs.readdirSync(path.join(ROOT, "src"))) fs.copyFileSync(path.join(ROOT, "src", f), path.join(out, f));
  const icons = path.join(ROOT, "sites", id, "icons");
  for (const s of [16, 32, 48, 128]) fs.copyFileSync(path.join(icons, `${s}.png`), path.join(out, "icons", `${s}.png`));
  const config = { id: site.id, short: site.short, home: site.home, feed: site.feed, search: site.search, page: site.page, brand: site.brand, brandDark: site.brandDark };
  fs.writeFileSync(path.join(out, "config.js"), `// Generated by scripts/build.mjs from sites/${id}.json.\nconst CONFIG = ${JSON.stringify(config, null, 2)};\n`);
  fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifestFor(site), null, 2) + "\n");
  const zip = path.join(ROOT, "dist", `${id}-${site.version}.zip`);
  fs.rmSync(zip, { force: true });
  execFileSync("zip", ["-qr", "-X", zip, "."], { cwd: out });
  console.log(`${id}: ${path.relative(process.cwd(), zip)}`);
}
